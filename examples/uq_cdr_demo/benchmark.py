"""Generate the full CDR UQ comparison used by the documentation.

This script is intentionally separate from ``example.py`` so the normal example
and CI smoke test remain inexpensive. It assumes ``reference_stats.json`` has
already been generated by ``generate_reference.py``.
"""

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from example import (
    EXAMPLE_DIRECTORY,
    IntegratedFluxCdrModel,
    build_parameter_space,
)
from romtools.workflows.uq import run_monte_carlo, run_multifidelity_monte_carlo


BUDGETS = (40, 80, 160, 320)
PILOT_SAMPLE_COUNT = 30
LOW_TO_HIGH_COST_RATIO = 0.05
RANDOM_SEED = 7


def _relative_error(estimate: float, reference: float) -> float:
    return abs(estimate - reference) / abs(reference)


def main(output_directory: Path) -> None:
    output_directory = Path(output_directory).resolve()
    output_directory.mkdir(parents=True, exist_ok=True)

    with open(EXAMPLE_DIRECTORY / "reference_stats.json", encoding="utf-8") as handle:
        reference = json.load(handle)
    reference_mean = float(reference["mean"])

    parameter_space = build_parameter_space()
    high_model = IntegratedFluxCdrModel(nx=21, ny=21)
    low_model = IntegratedFluxCdrModel(nx=9, ny=9)
    records = []
    pilot_correlation = None

    for budget in BUDGETS:
        mc = run_monte_carlo(
            model=high_model,
            parameter_space=parameter_space,
            absolute_work_dir=str(output_directory / f"mc_budget_{budget}"),
            number_of_samples=budget,
            random_seed=RANDOM_SEED,
        )
        mf_directory = output_directory / f"mfmc_budget_{budget}"
        mfmc = run_multifidelity_monte_carlo(
            high_fidelity_model=high_model,
            low_fidelity_model=low_model,
            parameter_space=parameter_space,
            absolute_work_dir=str(mf_directory),
            pilot_sample_count=PILOT_SAMPLE_COUNT,
            high_fidelity_equivalent_budget=float(budget),
            low_to_high_fidelity_cost_ratio=LOW_TO_HIGH_COST_RATIO,
            allocation_qoi_index=0,
            random_seed=RANDOM_SEED,
        )
        with np.load(mf_directory / "uq_stats.npz") as statistics:
            rho = float(statistics["pilot_correlations"][0])
        if pilot_correlation is None:
            pilot_correlation = rho

        records.append(
            {
                "budget": budget,
                "mc": {
                    "high_fidelity_samples": budget,
                    "low_fidelity_samples": 0,
                    "mean": float(mc.mean[0]),
                    "standard_error": float(mc.standard_error[0]),
                    "relative_error": _relative_error(float(mc.mean[0]), reference_mean),
                },
                "mfmc": {
                    "high_fidelity_samples": mfmc.high_fidelity_sample_count,
                    "low_fidelity_samples": mfmc.low_fidelity_sample_count,
                    "mean": float(mfmc.mean[0]),
                    "standard_error": float(mfmc.standard_error[0]),
                    "relative_error": _relative_error(float(mfmc.mean[0]), reference_mean),
                    "high_fidelity_equivalent_cost": float(
                        mfmc.high_fidelity_equivalent_cost
                    ),
                },
            }
        )

    pilot_directory = output_directory / f"mfmc_budget_{BUDGETS[0]}"
    with np.load(pilot_directory / "uq_stats.npz") as statistics:
        high_pilot = statistics["high_fidelity_qoi_values"][:PILOT_SAMPLE_COUNT, 0]
        low_pilot = statistics["low_fidelity_qoi_values"][:PILOT_SAMPLE_COUNT, 0]

    figure, axis = plt.subplots()
    axis.scatter(low_pilot, high_pilot)
    fit = np.polyfit(low_pilot, high_pilot, 1)
    x_values = np.linspace(np.min(low_pilot), np.max(low_pilot), 100)
    axis.plot(x_values, np.polyval(fit, x_values))
    axis.set_xlabel("Low-fidelity pilot QoI")
    axis.set_ylabel("High-fidelity pilot QoI")
    axis.set_title(f"Pilot correlation: rho = {pilot_correlation:.3f}")
    figure.tight_layout()
    figure.savefig(output_directory / "uq_cdr_pilot_correlation.svg")
    plt.close(figure)

    figure, axis = plt.subplots()
    budgets = np.asarray([record["budget"] for record in records], dtype=float)
    mc_error = np.asarray([record["mc"]["relative_error"] for record in records])
    mfmc_error = np.asarray(
        [record["mfmc"]["relative_error"] for record in records]
    )
    axis.loglog(budgets, mc_error, marker="o", label="Monte Carlo")
    axis.loglog(budgets, mfmc_error, marker="s", label="Multifidelity Monte Carlo")
    axis.set_xlabel("High-fidelity-equivalent cost")
    axis.set_ylabel("Relative error in estimated mean")
    axis.grid(True, which="both")
    axis.legend()
    figure.tight_layout()
    figure.savefig(output_directory / "uq_cdr_convergence.svg")
    plt.close(figure)

    payload = {
        "reference": reference,
        "pilot_sample_count": PILOT_SAMPLE_COUNT,
        "pilot_correlation": pilot_correlation,
        "low_to_high_fidelity_cost_ratio": LOW_TO_HIGH_COST_RATIO,
        "records": records,
    }
    with open(output_directory / "benchmark_results.json", "w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2)
        handle.write("\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-directory",
        type=Path,
        default=EXAMPLE_DIRECTORY / "benchmark_output",
    )
    arguments = parser.parse_args()
    main(arguments.output_directory)
